N, a, b = map(int, input().split())
NEG = -10**30
m = [[a // 2, b // 2], [a, b]]
r = [[0, NEG], [NEG, 0]]
p = m
e = N
while e:
    if e & 1:
        r = [
            [max(r[0][0] + p[0][0], r[0][1] + p[1][0]), max(r[0][0] + p[0][1], r[0][1] + p[1][1])],
            [max(r[1][0] + p[0][0], r[1][1] + p[1][0]), max(r[1][0] + p[0][1], r[1][1] + p[1][1])],
        ]
    p = [
        [max(p[0][0] + p[0][0], p[0][1] + p[1][0]), max(p[0][0] + p[0][1], p[0][1] + p[1][1])],
        [max(p[1][0] + p[0][0], p[1][1] + p[1][0]), max(p[1][0] + p[0][1], p[1][1] + p[1][1])],
    ]
    e >>= 1
print(max(r[1][0], r[1][1]))
